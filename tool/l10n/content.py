"""Puts the level packs' texts (episode names, level names, tutorials) into
lib/l10n/app_en.arb and writes lib/l10n/content.dart, which looks them up
by number. Run it after changing those texts in assets/levels/, then
translate the new or changed keys in the other app_*.arb files.

    python3 tool/l10n/content.py
"""
import glob
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ARB = os.path.join(ROOT, 'lib/l10n/app_en.arb')
DART = os.path.join(ROOT, 'lib/l10n/content.dart')

packs = sorted(glob.glob(os.path.join(ROOT, 'assets/levels/episode*.json')),
               key=lambda p: int(re.findall(r'\d+', os.path.basename(p))[0]))
content = {}
episodes, names, tutorials = [], [], []
for i, p in enumerate(packs, 1):
    pack = json.load(open(p, encoding='utf-8'))
    content[f'episode{i}'] = pack['episode']
    content[f'@episode{i}'] = {'description': 'Name of world (episode) %d on the level map.' % i}
    episodes.append(i)
    for lv in pack['levels']:
        n = lv['id']
        content[f'levelName{n}'] = lv['name']
        content[f'@levelName{n}'] = {'description': 'Short, playful title of level %d.' % n}
        names.append(n)
        if lv.get('tutorial'):
            content[f'tutorial{n}'] = lv['tutorial']
            content[f'@tutorial{n}'] = {
                'description': 'Tutorial card text shown at the start of level %d '
                               '(teaches a new mechanic; keep it short).' % n}
            tutorials.append(n)

arb = json.load(open(ARB, encoding='utf-8'))
for k in [k for k in arb if re.fullmatch(r'@?(episode|levelName|tutorial)\d+', k)]:
    del arb[k]
arb.update(content)
with open(ARB, 'w', encoding='utf-8') as f:
    json.dump(arb, f, ensure_ascii=False, indent=2)
    f.write('\n')


def switch(fn, keys, prefix):
    cases = '\n'.join(f'    {k} => t.{prefix}{k},' for k in keys)
    return f'String? {fn}(AppStrings t, int n) => switch (n) {{\n{cases}\n    _ => null,\n}};\n'


with open(DART, 'w', encoding='utf-8') as f:
    f.write('''// Generated by tool/l10n/content.py from assets/levels/. Do not edit.

import '../app/level_repository.dart';
import '../core/level.dart';
import 'l10n.dart';

/// [level]'s name in the current language. A level whose name is not the
/// bundled one (from the editor or remote config) keeps its own.
String levelName(LevelDef level) =>
    _same(levelNameOf, level.id, level.name) ?? level.name;

/// [level]'s tutorial text in the current language, if it has one.
String? tutorialText(LevelDef level) {
  final t = level.tutorial;
  return t == null ? null : _same(tutorialOf, level.id, t) ?? t;
}

/// The world's name in the current language.
String episodeName(Episode e) =>
    _same(episodeOf, e.index + 1, e.name) ?? e.name;

String? _same(String? Function(AppStrings, int) of, int n, String text) =>
    of(Lang.english, n) == text ? of(tr, n) : null;

''')
    f.write(switch('episodeOf', episodes, 'episode') + '\n')
    f.write(switch('levelNameOf', names, 'levelName') + '\n')
    f.write(switch('tutorialOf', tutorials, 'tutorial'))
print(len(episodes), 'episodes', len(names), 'levels', len(tutorials), 'tutorials')
